// scripts/generate-viewer-vendor.js
// Regenerates src/services/documentViewers/vendor/*.generated.ts — plain
// string-export modules wrapping the minified library sources the in-app
// PDF/DOCX viewers inject into their WebView HTML at runtime.
//
// Why vendored-as-a-string instead of a normal npm runtime dependency:
// these libraries never run in the RN/Hermes JS thread. They run inside
// react-native-webview's own DOM/JS engine (a real browser environment),
// concatenated straight into a <script> tag we build ourselves — see
// src/services/documentViewers/pdfViewerHtml.ts and docxViewerHtml.ts.
// Fetching them from a CDN at runtime is not an option: this app's
// android.permission.INTERNET is explicitly blocked in app.json (a vault
// app has no business making network requests), so every byte the
// WebView ever loads has to already be inside the JS bundle.
//
// pdfjs-dist is pinned to 3.11.174 specifically because it's the last
// series to ship classic (non-ESM) UMD builds — legacy/build/pdf.min.js
// sets a plain `window.pdfjsLib` global and legacy/build/pdf.worker.min.js
// is a classic (non-`type: module`) Worker script. Newer pdfjs-dist only
// ships .mjs (ES module) builds, which would require ES-module Worker
// support in the target WebView (Android System WebView's support is
// fine, iOS WKWebView's has historically been inconsistent) — classic
// scripts/workers side-step that entirely and just work everywhere.
//
// Re-run `node scripts/generate-viewer-vendor.js` after bumping either
// dependency's devDependency version in package.json.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'src', 'services', 'documentViewers', 'vendor');

const SOURCES = [
  {
    src: path.join(ROOT, 'node_modules', 'pdfjs-dist', 'legacy', 'build', 'pdf.min.js'),
    out: path.join(OUT_DIR, 'pdfLibSource.generated.ts'),
    banner: '// AUTO-GENERATED by scripts/generate-viewer-vendor.js from pdfjs-dist/legacy/build/pdf.min.js — do not hand-edit.\n// This is pdf.js\'s core library (no viewer UI), exposing a global `pdfjsLib`\n// when evaluated. Injected verbatim into the PDF WebView\'s inline <script>.\n',
  },
  {
    src: path.join(ROOT, 'node_modules', 'pdfjs-dist', 'legacy', 'build', 'pdf.worker.min.js'),
    out: path.join(OUT_DIR, 'pdfWorkerSource.generated.ts'),
    banner: '// AUTO-GENERATED by scripts/generate-viewer-vendor.js from pdfjs-dist/legacy/build/pdf.worker.min.js — do not hand-edit.\n// Loaded as a classic (non-module) Worker via a Blob URL — see pdfViewerHtml.ts.\n',
  },
  {
    src: path.join(ROOT, 'node_modules', 'mammoth', 'mammoth.browser.min.js'),
    out: path.join(OUT_DIR, 'mammothLibSource.generated.ts'),
    banner: '// AUTO-GENERATED by scripts/generate-viewer-vendor.js from mammoth/mammoth.browser.min.js — do not hand-edit.\n// Browser build of mammoth.js (docx -> HTML), exposing a global `mammoth`.\n// Injected verbatim into the DOCX WebView\'s inline <script>.\n',
  },
];

fs.mkdirSync(OUT_DIR, { recursive: true });

for (const { src, out, banner } of SOURCES) {
  const content = fs.readFileSync(src, 'utf8');
  const body = `${banner}export default ${JSON.stringify(content)};\n`;
  fs.writeFileSync(out, body, 'utf8');
  console.log(`wrote ${path.relative(ROOT, out)} (${(content.length / 1024).toFixed(0)} KB source)`);
}
